def gen_tput_file():
    """Generate gen_tput.cu — throughput ILP sweep for all instructions."""
    parts = [HEADER]
    entries = []

    for insn in INSTRUCTIONS:
        for ilp in ILP_LEVELS:
            parts.append(gen_tput_kernel(insn, ilp))
            parts.append('')
            iid = insn['id']
            ratio = insn.get('sass_ratio', 1.0)
            sass_insns = max(1, int(ilp * ratio))
            entries.append(f'    {{"{iid} tput ilp={ilp}", {sass_insns}, tput_{iid}_ilp{ilp}}},')

    parts.append(MAIN_PREAMBLE)
    parts.append('    Bench benches[] = {')
    parts.extend(entries)
    parts.append('    };')
    parts.append(MAIN_LOOP)

    path = os.path.join(OUTDIR, 'gen_tput.cu')
    with open(path, 'w') as f:
        f.write('\n'.join(parts))
    print(f'Generated {path} ({len(entries)} kernels)')


def gen_lat_file():
    """Generate gen_lat.cu — latency for all supported instructions."""
    parts = [HEADER]
    entries = []

    for insn in INSTRUCTIONS:
        if insn['type'] in ('sts', 'stg'):
            continue
        parts.append(gen_lat_kernel(insn))
        parts.append('')
        iid = insn['id']
        entries.append(f'    {{"{iid} lat depth={LAT_DEPTH}", {LAT_DEPTH}, lat_{iid}}},')

    parts.append(MAIN_PREAMBLE)
    parts.append('    Bench benches[] = {')
    parts.extend(entries)
    parts.append('    };')
    parts.append(MAIN_LOOP)

    path = os.path.join(OUTDIR, 'gen_lat.cu')
    with open(path, 'w') as f:
        f.write('\n'.join(parts))
    print(f'Generated {path} ({len(entries)} kernels)')


def gen_conflict_file():
    """Generate gen_conflict.cu — NxN conflict matrix."""
    parts = [HEADER]
    entries = []

    pairs = list(combinations(INSTRUCTIONS, 2))
    for insn_a, insn_b in pairs:
        parts.append(_gen_conflict_kernel(insn_a, insn_b))
        parts.append('')
        ida, idb = insn_a['id'], insn_b['id']
        entries.append(f'    {{"{ida} x {idb}", {CONFLICT_CHAINS * 2},'
                       f' conf_{ida}_{idb}}},')

    parts.append(MAIN_PREAMBLE)
    parts.append('    Bench benches[] = {')
    parts.extend(entries)
    parts.append('    };')
    parts.append(MAIN_LOOP)

    path = os.path.join(OUTDIR, 'gen_conflict.cu')
    with open(path, 'w') as f:
        f.write('\n'.join(parts))
    print(f'Generated {path} ({len(entries)} pairs)')


