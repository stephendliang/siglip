def _sts_tput(ilp):
    o = []
    o.append(f'extern "C" __global__ void tput_STS_ilp{ilp}(long long* out) {{')
    o.append(f'    __shared__ int _smem[1024];')
    o.append(f'    int _tid = threadIdx.x;')
    o.append(f'    uint32_t _base = (uint32_t)(uint64_t)(&_smem[_tid * 16]);')
    o.append(f'    unsigned _v0=0xdeadbeef, _v1=0xcafebabe, _v2=0x12345678, _v3=0x9abcdef0;')
    o.append(f'    for (int _w = 0; _w < WARMUP; _w++)')
    o.append(f'        asm volatile("st.shared.b32 [%0], %1;" :: "r"(_base), "r"(_v0));')
    o.append(f'    long long t0 = clock64();')
    o.append(f'    for (int _i = 0; _i < REPS; _i++) {{')
    o.append(f'        asm volatile(')
    offsets = [0, 16, 32, 48]
    for i in range(ilp):
        off = offsets[i % 4]
        if off == 0:
            o.append(f'            "st.shared.v4.b32 [%0], {{%1,%2,%3,%4}};\\n\\t"')
        else:
            o.append(f'            "st.shared.v4.b32 [%0+{off}], {{%1,%2,%3,%4}};\\n\\t"')
