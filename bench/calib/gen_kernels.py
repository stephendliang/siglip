def _f2fp_tput(ilp):
    n_src = min(ilp, 8)
    src_base = ilp
    o = []
    o.append(f'extern "C" __global__ void tput_F2FP_ilp{ilp}(long long* out) {{')
    o.append(f'    volatile unsigned* gin = (volatile unsigned*)out;')
    o.append(f'    volatile unsigned* _fin = (volatile unsigned*)(out + 16);')
    for i in range(ilp):
        o.append(f'    unsigned _a{i} = gin[{i}];')
    for j in range(n_src):
        o.append(f'    unsigned _f{j} = _fin[{j}];')
    o.append(f'    for (int _w = 0; _w < WARMUP; _w++)')
    o.append(f'        asm volatile("{{ .reg .f32 _fa, _fb; mov.b32 _fa, %0; mov.b32 _fb, %1;'
             f' cvt.rn.bf16x2.f32 %0, _fa, _fb; }}" : "+r"(_a0) : "r"(_f0));')
    o.append(f'    long long t0 = clock64();')
    o.append(f'    for (int _i = 0; _i < REPS; _i++) {{')
    o.append(f'        asm volatile(')
    o.append(f'            "{{ .reg .f32 _fa, _fb;\\n\\t"')
    for i in range(ilp):
        si = src_base + (i % n_src)
        o.append(f'            "mov.b32 _fa, %{i}; mov.b32 _fb, %{si};'
                 f' cvt.rn.bf16x2.f32 %{i}, _fa, _fb;\\n\\t"')
    o.append(f'            "}}\\n\\t"')
    ocon = ', '.join(f'"+r"(_a{i})' for i in range(ilp))
    icon = ', '.join(f'"r"(_f{j})' for j in range(n_src))
    o.append(f'            : {ocon}')
    o.append(f'            : {icon}')
    o.append(f'        );')
    o.append(f'    }}')
    o.append(f'    long long t1 = clock64();')
    asum = ' + '.join(f'_a{i}' for i in range(ilp))
    o.append(f'    if (threadIdx.x == 0) {{ out[0] = t1 - t0; out[1] = {asum}; }}')
    o.append(f'}}')
    return '\n'.join(o)


