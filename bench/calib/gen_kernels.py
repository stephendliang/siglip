def _conflict_half_size(insn):
    """Return (n_acc, n_src) for this instruction in a conflict test with CONFLICT_CHAINS."""
    t = insn['type']
    n = CONFLICT_CHAINS
    if t == 'alu':
        return (n, len(insn['srcs']))
    elif t == 'f2fp':
        return (n, min(n, 8))
    elif t == 'sel':
        return (n, 1)  # one source (_sv)
    elif t == 'sts':
        return (0, 5)  # addr + 4 store values
    elif t == 'stg':
        return (0, 2)  # base_ptr(l) + val(r)
    elif t in ('lds', 'ldg'):
        return (n, 1)  # base addr/ptr
    return (0, 0)


def _conflict_half_decls(insn, prefix):
    """Generate C declarations for one side of a conflict test."""
    t = insn['type']
    n = CONFLICT_CHAINS
    p = prefix
    lines = []
    if t == 'alu':
        acc_ct = insn['acc'][0]
        gin_cast = insn['gin']
        lines.append(f'    {gin_cast} {p}gin = ({gin_cast})out;')
        for i in range(n):
            lines.append(f'    {acc_ct} {p}a{i} = {p}gin[{i}]+({i}+1);')
        for j, (sct, _) in enumerate(insn['srcs']):
            lines.append(f'    {sct} {p}s{j} = {p}gin[threadIdx.x+{j*32}];')
    elif t == 'f2fp':
        lines.append(f'    volatile unsigned* {p}gin = (volatile unsigned*)out;')
        lines.append(f'    volatile unsigned* {p}fin = (volatile unsigned*)(out + 16);')
        for i in range(n):
            lines.append(f'    unsigned {p}a{i} = {p}gin[{i}];')
        ns = min(n, 8)
        for j in range(ns):
            lines.append(f'    unsigned {p}f{j} = {p}fin[{j}];')
    elif t == 'sel':
        lines.append(f'    volatile int* {p}gin = (volatile int*)out;')
        lines.append(f'    int {p}cond = {p}gin[threadIdx.x] | 1;')
        lines.append(f'    int {p}sv = {p}gin[threadIdx.x + 32];')
        for i in range(n):
            lines.append(f'    int {p}a{i} = {p}gin[{i}]+({i}+1);')
        lines.append(f'    asm volatile(".reg .pred {p}kp;");')
        lines.append(f'    asm volatile("setp.ne.s32 {p}kp, %0, 0;" :: "r"({p}cond));')
    elif t == 'sts':
        lines.append(f'    __shared__ int {p}smem[1024];')
        lines.append(f'    uint32_t {p}addr = (uint32_t)(uint64_t)(&{p}smem[threadIdx.x*16]);')
        lines.append(f'    unsigned {p}v0=0xdead, {p}v1=0xcafe, {p}v2=0x1234, {p}v3=0x9abc;')
    elif t == 'stg':
        lines.append(f'    char* {p}base = (char*)(out + 128) + threadIdx.x * 64;')
        lines.append(f'    int {p}val = threadIdx.x + 1;')
    elif t == 'lds':
        lines.append(f'    __shared__ int {p}smem[1024];')
        lines.append(f'    for (int _k = 0; _k < 32; _k++)')
        lines.append(f'        {p}smem[threadIdx.x + _k*32] = threadIdx.x + _k;')
        lines.append(f'    __syncthreads();')
        lines.append(f'    uint32_t {p}addr = (uint32_t)(uint64_t)(&{p}smem[threadIdx.x]);')
        lines.append(f'    volatile int* {p}gin = (volatile int*)out;')
        for i in range(n):
            lines.append(f'    int {p}a{i} = {p}gin[{i}];')
    elif t == 'ldg':
        lines.append(f'    const int* {p}data = (const int*)(out + 64);')
        lines.append(f'    volatile int* {p}gin = (volatile int*)out;')
        for i in range(n):
            lines.append(f'    int {p}a{i} = {p}gin[{i}];')
    return lines


def _conflict_half_ptx(insn, prefix, acc_base, src_base, chain_idx):
    """Generate one PTX line for chain chain_idx of this instruction."""
    t = insn['type']
    n = CONFLICT_CHAINS
    i = chain_idx
    if t == 'alu':
        subs = {'A': str(acc_base + i)}
        for j in range(len(insn['srcs'])):
            subs[f'S{j}'] = str(src_base + j)
        return insn['ptx'].format(**subs)
    elif t == 'f2fp':
        ns = min(n, 8)
        a = acc_base + i
        s = src_base + (i % ns)
        return f'mov.b32 _fa, %{a}; mov.b32 _fb, %{s}; cvt.rn.bf16x2.f32 %{a}, _fa, _fb;'
    elif t == 'sel':
        a = acc_base + i
        s = src_base
        return f'selp.b32 _st, %{a}, %{s}, {prefix}kp; add.s32 %{a}, %{a}, _st;'
    elif t == 'sts':
        off = (i % 4) * 16
        s = src_base
        return (f'st.shared.v4.b32 [%{s}+{off}],'
                f' {{%{s+1},%{s+2},%{s+3},%{s+4}}};')
    elif t == 'stg':
        off = (i * 4) % 64
        return f'st.global.b32 [%{src_base}+{off}], %{src_base+1};'
    elif t == 'lds':
        a = acc_base + i
        off = i * 128
        return f'ld.volatile.shared.b32 _lt, [%{src_base}+{off}]; xor.b32 %{a}, %{a}, _lt;'
    elif t == 'ldg':
        a = acc_base + i
        return f'ld.global.b32 _gt, [%{src_base}+{i*4}]; xor.b32 %{a}, %{a}, _gt;'
    return ''


def _conflict_half_cons(insn, prefix, n):
    """Return (out_constraints, in_constraints) lists of strings."""
    t = insn['type']
    outs, ins = [], []
    if t == 'alu':
        con = insn['acc'][1]
        for i in range(n):
            outs.append(f'"+{con}"({prefix}a{i})')
        for j, (_, sc) in enumerate(insn['srcs']):
            ins.append(f'"{sc}"({prefix}s{j})')
    elif t == 'f2fp':
        for i in range(n):
            outs.append(f'"+r"({prefix}a{i})')
        ns = min(n, 8)
        for j in range(ns):
            ins.append(f'"r"({prefix}f{j})')
    elif t == 'sel':
        for i in range(n):
            outs.append(f'"+r"({prefix}a{i})')
        ins.append(f'"r"({prefix}sv)')
    elif t == 'sts':
        ins.extend([
            f'"r"({prefix}addr)',
            f'"r"({prefix}v0)', f'"r"({prefix}v1)',
            f'"r"({prefix}v2)', f'"r"({prefix}v3)',
        ])
    elif t == 'stg':
        ins.extend([f'"l"({prefix}base)', f'"r"({prefix}val)'])
    elif t == 'lds':
        for i in range(n):
            outs.append(f'"+r"({prefix}a{i})')
        ins.append(f'"r"({prefix}addr)')
    elif t == 'ldg':
        for i in range(n):
            outs.append(f'"+r"({prefix}a{i})')
        ins.append(f'"l"({prefix}data)')
    return outs, ins


def _conflict_ptx_regs(insn_a, insn_b):
    """Get combined .reg declarations needed for a conflict pair."""
    regs = []
    for insn in (insn_a, insn_b):
        if insn['type'] == 'f2fp':
            regs.extend(['.reg .f32 _fa', '.reg .f32 _fb'])
        elif insn['type'] == 'sel':
            regs.extend(['.reg .b32 _st'])
        elif insn['type'] == 'lds':
            regs.extend(['.reg .s32 _lt'])
        elif insn['type'] == 'ldg':
            regs.extend(['.reg .s32 _gt'])
    seen = set()
    unique = []
    for r in regs:
        if r not in seen:
            seen.add(r)
            unique.append(r)
    return unique


def _gen_conflict_kernel(insn_a, insn_b):
    """Generate a conflict kernel for two instructions."""
    ida, idb = insn_a['id'], insn_b['id']
    n = CONFLICT_CHAINS
    na_acc, na_src = _conflict_half_size(insn_a)
    nb_acc, nb_src = _conflict_half_size(insn_b)
    total_out = na_acc + nb_acc
    a_src_base = total_out
    b_src_base = total_out + na_src

    o = []
    o.append(f'extern "C" __global__ void conf_{ida}_{idb}(long long* out) {{')

    # declarations
    o.extend(_conflict_half_decls(insn_a, 'a_'))
    o.extend(_conflict_half_decls(insn_b, 'b_'))

    # timed loop
    o.append(f'    long long t0 = clock64();')
    o.append(f'    for (int _i = 0; _i < REPS; _i++) {{')
    o.append(f'        asm volatile(')

    # ptx reg declarations
    ptx_regs = _conflict_ptx_regs(insn_a, insn_b)
    if ptx_regs:
        decl_str = '; '.join(ptx_regs) + ';'
        o.append(f'            "{{ {decl_str}\\n\\t"')
    for i in range(n):
        ptx_a = _conflict_half_ptx(insn_a, 'a_', 0, a_src_base, i)
        ptx_b = _conflict_half_ptx(insn_b, 'b_', na_acc, b_src_base, i)
        o.append(f'            "{ptx_a}\\n\\t"')
        o.append(f'            "{ptx_b}\\n\\t"')
    if ptx_regs:
        o.append(f'            "}}\\n\\t"')

    # constraints
    outs_a, ins_a = _conflict_half_cons(insn_a, 'a_', n)
    outs_b, ins_b = _conflict_half_cons(insn_b, 'b_', n)
    all_outs = outs_a + outs_b
    all_ins = ins_a + ins_b
    needs_mem = insn_a['type'] in ('sts', 'stg') or insn_b['type'] in ('sts', 'stg')

    if all_outs:
        o.append(f'            : {", ".join(all_outs)}')
    else:
        o.append(f'            :')
    if all_ins:
        o.append(f'            : {", ".join(all_ins)}')
    if needs_mem:
        if not all_ins:
            o.append(f'            :')
        o.append(f'            : "memory"')
    o.append(f'        );')
    o.append(f'    }}')
    o.append(f'    long long t1 = clock64();')

    # sink
    sink_parts = []
    if na_acc > 0:
        acc_ct = 'float' if insn_a['type'] == 'alu' and insn_a['acc'][0] == 'float' else 'int'
        asum = ' + '.join(f'a_a{i}' for i in range(n))
        if acc_ct == 'float':
            sink_parts.append(f'    volatile float* _fo = (volatile float*)(out + 1); _fo[0] = {asum};')
        else:
            sink_parts.append(f'    out[1] = {asum};')
    if nb_acc > 0:
        acc_ct = 'float' if insn_b['type'] == 'alu' and insn_b['acc'][0] == 'float' else 'int'
        bsum = ' + '.join(f'b_a{i}' for i in range(n))
        if acc_ct == 'float':
            sink_parts.append(f'    volatile float* _fo2 = (volatile float*)(out + 2); _fo2[0] = {bsum};')
        else:
            sink_parts.append(f'    out[2] = {bsum};')

    o.append(f'    if (threadIdx.x == 0) {{')
    o.append(f'        out[0] = t1 - t0;')
    for sp in sink_parts:
        o.append(sp)
    o.append(f'    }}')
    o.append(f'}}')
    return '\n'.join(o)


