def _alu_tput(insn, ilp):
    """Generate throughput kernel for an ALU instruction at given ILP."""
    iid = insn['id']
    acc_ct, acc_con = insn['acc']
    srcs = insn['srcs']
    ptx = insn['ptx']
    gin_cast = insn['gin']
    n_src = len(srcs)
    src_base = ilp

    o = []
    o.append(f'extern "C" __global__ void tput_{iid}_ilp{ilp}(long long* out) {{')
    o.append(f'    {gin_cast} gin = ({gin_cast})out;')
    for i in range(ilp):
        o.append(f'    {acc_ct} _a{i} = {insn["init"].format(i=i)};')
    for j, (sct, _) in enumerate(srcs):
        o.append(f'    {sct} _s{j} = {insn["si"][j]};')

    # warmup
    wsubs = {'A': '0'}
    for j in range(n_src):
        wsubs[f'S{j}'] = str(1 + j)
    wptx = ptx.format(**wsubs)
    wout = f'"+{acc_con}"(_a0)'
    wins = ', '.join(f'"{sc}"(_s{j})' for j, (_, sc) in enumerate(srcs))
    wcon = wout + (f' : {wins}' if wins else '')
    o.append(f'    for (int _w = 0; _w < WARMUP; _w++)')
    o.append(f'        asm volatile("{wptx}" : {wcon});')

    # timed loop
    o.append(f'    long long t0 = clock64();')
    o.append(f'    for (int _i = 0; _i < REPS; _i++) {{')
    o.append(f'        asm volatile(')
    for i in range(ilp):
        subs = {'A': str(i)}
        for j in range(n_src):
            subs[f'S{j}'] = str(src_base + j)
        o.append(f'            "{ptx.format(**subs)}\\n\\t"')
    ocon = ', '.join(f'"+{acc_con}"(_a{i})' for i in range(ilp))
    icon = ', '.join(f'"{sc}"(_s{j})' for j, (_, sc) in enumerate(srcs))
    o.append(f'            : {ocon}')
    if icon:
        o.append(f'            : {icon}')
    o.append(f'        );')
    o.append(f'    }}')
    o.append(f'    long long t1 = clock64();')

    # sink
    asum = ' + '.join(f'_a{i}' for i in range(ilp))
    o.append(f'    if (threadIdx.x == 0) {{')
    o.append(f'        out[0] = t1 - t0;')
    if acc_ct == 'float':
        o.append(f'        volatile float* _fo = (volatile float*)(out + 1);')
        o.append(f'        _fo[0] = {asum};')
    else:
        o.append(f'        out[1] = {asum};')
    o.append(f'    }}')
    o.append(f'}}')
    return '\n'.join(o)


