/*
  gemm_w3x_body.cuh — shared body for the w3x FC1/FC2 kernels.

  fc1_w3x.cu and fc2_w3x.cu are the same 6-warp rank-1-shaped persistent
  GEMM (W0-W3 epi / W4 TMA / W5 MMA-CTA0-only, register-cached bias
  preload, swizzle LUT, 4D packed-tile output ABI). They diverged only in
  geometry and epilogue activation, so the whole kernel + harness lives
  here once and the two .cu files are thin shims that #define their
  identity before including this header:

      fc2_w3x.cu:  #define W3X_FC2   (then include)   -> N=768  K=3072, bias-only
      fc1_w3x.cu:  #define W3X_FC1   (then include)   -> N=3072 K=768,  GELU+BIAS

  Everything FC1/FC2-specific is gated on W3X_FC1: N_DIM/K_DIM, K_STAGGER,
  the N_STAGES picker (fc1 hard-codes 5 under NO_PREFILL; fc2 auto-picks),
  the SUBPASS_CHUNKS/WIDE_SUBPASS path, the CVT epilogue macro (GELU+BIAS
  vs plain bias-add), the bias_switch_inc_<48|12> include, and the golden
  verify. Edit the shared body once; both kernels rebuild.

  This file was generated by diffing the two originals (scratchpad
  merge_w3x.py) and is maintained by hand thereafter.
*/

